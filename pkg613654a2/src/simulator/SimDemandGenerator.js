/**
 * Emits one leg of demand: expected riders, apportioned over origins, destinations and time, then
 * materialized as journeys with a matching trace entry.
 */
function emitLeg(ctx) {
  if (ctx.windowStartMs === null || ctx.windowEndMs === null) { return; }
  var attendance = (ctx.attendance === null || ctx.attendance === undefined) ? 0 : ctx.attendance;
  var share = (ctx.busUseShare === null || ctx.busUseShare === undefined) ? 1.0 : ctx.busUseShare;
  var expected = attendance * share * ctx.weight;
  var totalPax = Math.round(expected);

  var origins = normalize(ctx.originDist);
  var dests = normalize(ctx.destDist);

  var traceEntry = {
    expectedPassengers: expected,
    generatedPassengers: 0,
    journeyIds: []
  };

  if (totalPax > 0 && origins.length > 0 && dests.length > 0) {
    var windowStart = ctx.windowStartMs;
    var windowEnd = Math.max(ctx.windowEndMs, ctx.windowStartMs);
    var windowLen = windowEnd - windowStart;
    var buckets = bucketCount(windowLen);

    var byOrigin = apportion(totalPax, origins);
    var idx = 0;

    for (var o = 0; o < origins.length; o++) {
      if (byOrigin[o] <= 0) { continue; }
      var byDest = apportion(byOrigin[o], dests);
      for (var d = 0; d < dests.length; d++) {
        if (byDest[d] <= 0) { continue; }
        if (origins[o].stopId === dests[d].stopId) {
          // A journey that starts where it ends consumes no bus capacity; dropping it silently
          // would break the accounting identity, so it is folded into the next destination share.
          continue;
        }
        var perBucket = apportionEven(byDest[d], buckets);
        for (var b = 0; b < buckets; b++) {
          if (perBucket[b] <= 0) { continue; }
          var requestMs = bucketTime(windowStart, windowLen, buckets, b, ctx.assumptions, ctx.rng);
          var originStopId = origins[o].stopId;
          var note = null;
          var relocated = false;
          var reloc = ctx.relocation[originStopId];
          if (reloc && requestMs >= reloc.startMs && requestMs < reloc.endMs) {
            originStopId = reloc.fallbackStopId;
            relocated = true;
            note = 'Origin moved from closed stop ' + origins[o].stopId + ' to pre-configured fallback '
              + reloc.fallbackStopId + ' (event ' + reloc.eventId + '). The fallback was known before the planning cutoff.';
          }
          if (originStopId === dests[d].stopId) { continue; }

          var jid = 'j_' + ctx.sourceId + '_' + ctx.legKind + '_' + idx;
          idx++;
          var j = SimPassengerJourney.make({
            journeyId: jid,
            cohortId: ctx.cohortId,
            passengerCount: perBucket[b],
            originStopId: originStopId,
            destinationStopId: dests[d].stopId,
            requestTime: DateTime.fromMillis(requestMs),
            classDeadline: ctx.deadlineMs === null ? null : DateTime.fromMillis(ctx.deadlineMs),
            hasDeadline: ctx.deadlineMs !== null,
            legKind: ctx.legKind,
            sourceKind: ctx.sourceKind,
            sourceEventId: ctx.sourceKind === 'Event' ? ctx.sourceId : null,
            sourceEstimateId: ctx.sourceKind === 'LocationEstimate' ? ctx.sourceId : null,
            appliedWeight: ctx.weight,
            rawExpectedCount: expected,
            wasRelocated: relocated,
            generationNote: note
          });
          ctx.journeys.push(j);
          traceEntry.generatedPassengers += perBucket[b];
          traceEntry.journeyIds.push(jid);
        }
      }
    }
  }

  ctx.trace.push(SimDemandTraceEntry.make({
    sourceEventId: ctx.sourceKind === 'Event' ? ctx.sourceId : null,
    sourceEstimateId: ctx.sourceKind === 'LocationEstimate' ? ctx.sourceId : null,
    sourceKind: ctx.sourceKind,
    legKind: ctx.legKind,
    journeyIds: traceEntry.journeyIds,
    attendance: attendance,
    busUseShare: share,
    appliedWeight: ctx.weight,
    expectedPassengers: expected,
    generatedPassengers: traceEntry.generatedPassengers,
    policy: 'expected = attendance * busUseShare * appliedWeight, rounded, then split across origins, '
      + 'destinations and arrival buckets by largest-remainder apportionment so rounding neither loses '
      + 'nor invents a passenger. Reliability policy: ' + ctx.policy
      + '. Arrival spread: ' + (ctx.assumptions.arrivalWindowDistribution || 'UniformDeterministic') + '.',
    windowStart: DateTime.fromMillis(ctx.windowStartMs),
    windowEnd: DateTime.fromMillis(ctx.windowEndMs)
  }));
}

/**
 * Reads the reconciliation decisions the assembler already made, so demand generation applies them
 * rather than re-deriving them and risking a different answer.
 */
function readTrace(input) {
  var out = {
    weightByEventId: {},
    cohortSuppressedEventIds: {},
    suppressedEstimateIds: {},
    reliabilityPolicy: 'None',
    defaultConfidence: 0.7,
    defaultReputation: 0.5
  };
  var a = input.assumptions;
  if (a) {
    out.reliabilityPolicy = a.reliabilityPolicy || 'None';
    if (a.defaultConfidence !== null && a.defaultConfidence !== undefined) { out.defaultConfidence = a.defaultConfidence; }
    if (a.defaultReputation !== null && a.defaultReputation !== undefined) { out.defaultReputation = a.defaultReputation; }
  }
  var tr = input.reconciliation;
  if (!tr || !tr.entries) { return out; }
  var entries = tr.entries;
  for (var i = 0; i < entries.length; i++) {
    var e = entries[i];
    if (e.entryKind === 'ReliabilityWeightApplied' && e.targetEventId) {
      out.weightByEventId[e.targetEventId] = e.appliedWeight;
    }
    if (e.entryKind === 'CohortOverlapResolved') {
      if (e.appliedWeight === 0 && e.targetEventId) {
        out.cohortSuppressedEventIds[e.targetEventId] = true;
      }
      var sup = e.supersededEstimateIds || [];
      for (var s = 0; s < sup.length; s++) { out.suppressedEstimateIds[sup[s]] = true; }
    }
    if (e.entryKind === 'EstimateSuperseded') {
      var sup2 = e.supersededEstimateIds || [];
      for (var s2 = 0; s2 < sup2.length; s2++) { out.suppressedEstimateIds[sup2[s2]] = true; }
    }
  }
  return out;
}

function weightForEstimate(est, facts, input) {
  var policy = facts.reliabilityPolicy;
  var conf = (est.confidence === null || est.confidence === undefined) ? facts.defaultConfidence : est.confidence;
  var rep = facts.defaultReputation;
  if (policy === 'None') { return 1.0; }
  if (policy === 'ConfidenceOnly') { return conf; }
  if (policy === 'ReputationOnly') { return rep; }
  // The estimator is a model, not a reporting user, so there is no user reputation to multiply in.
  // Under ConfidenceTimesReputation its own confidence is used unmodified and that choice is traced.
  return conf;
}

/**
 * Pre-configured closure fallbacks, restricted to closures already known at the planning cutoff.
 * A closure discovered mid-day has no legitimate fallback, so its passengers are reported unserved
 * rather than quietly moved to another stop.
 */
function buildRelocationMap(input, cutoffMs) {
  var map = {};
  var events = input.events || [];
  for (var i = 0; i < events.length; i++) {
    var ev = events[i];
    if (ev.canonicalEventId || ev.supersededByEventId) { continue; }
    if (msOf(ev.knownAt) > cutoffMs) { continue; }
    var effects = ev.operationalEffects || [];
    for (var j = 0; j < effects.length; j++) {
      var ef = effects[j];
      if (ef.effectKind !== 'StopUnavailable' || !ef.fallbackStopId) { continue; }
      var startMs = msOf(ef.windowStart !== null && ef.windowStart !== undefined ? ef.windowStart : ev.startTime);
      var endMs = msOf(ef.windowEnd !== null && ef.windowEnd !== undefined ? ef.windowEnd : ev.endTime);
      var stops = ef.stopIds || [];
      for (var k = 0; k < stops.length; k++) {
        if (!map[stops[k]]) {
          map[stops[k]] = {
            fallbackStopId: ef.fallbackStopId, startMs: startMs, endMs: endMs, eventId: ev.id
          };
        }
      }
    }
  }
  return map;
}

function normalize(dist) {
  if (!dist || dist.length === 0) { return []; }
  var total = 0;
  var i;
  for (i = 0; i < dist.length; i++) { total += dist[i].share; }
  var out = [];
  if (total <= 0) {
    for (i = 0; i < dist.length; i++) { out.push({ stopId: dist[i].stopId, share: 1.0 / dist.length }); }
    return out;
  }
  for (i = 0; i < dist.length; i++) { out.push({ stopId: dist[i].stopId, share: dist[i].share / total }); }
  return out;
}

/** Largest-remainder apportionment: the parts always sum back to total. */
function apportion(total, shares) {
  var counts = [];
  var rem = [];
  var assigned = 0;
  var i;
  for (i = 0; i < shares.length; i++) {
    var exact = total * shares[i].share;
    var floored = Math.floor(exact);
    counts.push(floored);
    rem.push({ i: i, r: exact - floored });
    assigned += floored;
  }
  var left = total - assigned;
  rem.sort(function (x, y) { return y.r - x.r !== 0 ? y.r - x.r : x.i - y.i; });
  for (i = 0; i < left; i++) { counts[rem[i % rem.length].i] += 1; }
  return counts;
}

function apportionEven(total, buckets) {
  var shares = [];
  for (var i = 0; i < buckets; i++) { shares.push({ share: 1.0 / buckets }); }
  return apportion(total, shares);
}

function bucketCount(windowLenMs) {
  var minutes = windowLenMs / 60000;
  if (minutes <= 0) { return 1; }
  var n = Math.floor(minutes / 5);
  if (n < 1) { n = 1; }
  if (n > 8) { n = 8; }
  return n;
}

function bucketTime(windowStart, windowLen, buckets, b, assumptions, rng) {
  if ((assumptions.arrivalWindowDistribution || 'UniformDeterministic') === 'SeededUniform') {
    var lo = windowStart + Math.floor(windowLen * b / buckets);
    var hi = windowStart + Math.floor(windowLen * (b + 1) / buckets);
    if (hi <= lo) { return lo; }
    return lo + Math.floor(rng() * (hi - lo));
  }
  return Math.round(windowStart + windowLen * (b + 0.5) / buckets);
}

/**
 * Small deterministic linear-congruential PRNG, only used when arrivalWindowDistribution is
 * SeededUniform. Written with plain arithmetic rather than typed-integer helpers so it behaves
 * identically on every JavaScript engine the platform may run this on.
 */
function makeRng(seed) {
  var s = (seed === null || seed === undefined) ? 1 : Math.abs(Math.floor(seed)) % 2147483647;
  if (s === 0) { s = 1; }
  return function () {
    s = (s * 48271) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

function minToMs(mins) {
  if (mins === null || mins === undefined) { return 0; }
  return mins * 60000;
}

function msOf(dt) {
  if (dt === null || dt === undefined) { return null; }
  if (typeof dt === 'number') { return dt; }
  return dt.toDate().getTime();
}
