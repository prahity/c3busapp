function snapshotId(scenarioId, seed) {
  return 'snap_' + scenarioId + '_' + seed;
}

function generate(input) {
  var a = input.assumptions;
  var seed = input.randomSeed;
  var rng = makeRng(seed);
  var horizonStartMs = msOf(input.horizonStart);
  var horizonEndMs = msOf(input.horizonEnd);
  var cutoffMs = msOf(input.planningCutoff);

  var policyFacts = readTrace(input);
  var journeys = [];
  var trace = [];
  var realizedEventIds = [];
  var unknownAtCutoff = [];
  var suppressedEventIds = [];

  // Relocation is only legitimate when a fallback was configured before the day started, so the
  // relocation map is built from planner-visible closures only.
  var relocation = buildRelocationMap(input, cutoffMs);

  var events = input.events || [];
  var i;
  for (i = 0; i < events.length; i++) {
    var ev = events[i];
    if (ev.canonicalEventId || ev.supersededByEventId) {
      suppressedEventIds.push(ev.id);
      continue;
    }
    if (policyFacts.cohortSuppressedEventIds[ev.id]) {
      suppressedEventIds.push(ev.id);
    }
    realizedEventIds.push(ev.id);
    if (msOf(ev.knownAt) > cutoffMs) { unknownAtCutoff.push(ev.id); }

    var de = ev.demandEffect;
    if (!de) { continue; }
    if (policyFacts.cohortSuppressedEventIds[ev.id]) { continue; }

    var weight = policyFacts.weightByEventId[ev.id];
    if (weight === null || weight === undefined) { weight = 1.0; }

    if (de.generatesInbound === true) {
      emitLeg({
        journeys: journeys, trace: trace, rng: rng, assumptions: a,
        sourceKind: 'Event', sourceId: ev.id, legKind: 'Inbound',
        attendance: de.attendance, busUseShare: de.busUseShare, weight: weight,
        originDist: de.originDistribution, destDist: de.destinationDistribution,
        windowStartMs: msOf(ev.startTime) + minToMs(de.inboundWindowStartOffsetMin),
        windowEndMs: msOf(ev.startTime) + minToMs(de.inboundWindowEndOffsetMin),
        deadlineMs: (de.classDeadlineOffsetMin === null || de.classDeadlineOffsetMin === undefined)
          ? null : msOf(ev.startTime) + minToMs(de.classDeadlineOffsetMin),
        cohortId: de.cohortId,
        policy: policyFacts.reliabilityPolicy,
        relocation: relocation,
        horizonStartMs: horizonStartMs, horizonEndMs: horizonEndMs
      });
    }

    if (de.generatesOutbound === true) {
      // On the outbound leg the distributions swap roles: riders leave the event location and
      // disperse to the stops they originally came from.
      emitLeg({
        journeys: journeys, trace: trace, rng: rng, assumptions: a,
        sourceKind: 'Event', sourceId: ev.id, legKind: 'Outbound',
        attendance: de.attendance, busUseShare: de.busUseShare, weight: weight,
        originDist: de.destinationDistribution, destDist: de.originDistribution,
        windowStartMs: msOf(ev.endTime) + minToMs(de.outboundWindowStartOffsetMin),
        windowEndMs: msOf(ev.endTime) + minToMs(de.outboundWindowEndOffsetMin),
        deadlineMs: null,
        cohortId: de.cohortId,
        policy: policyFacts.reliabilityPolicy,
        relocation: relocation,
        horizonStartMs: horizonStartMs, horizonEndMs: horizonEndMs
      });
    }
  }

  // Student-location estimates. Estimates that were superseded, or whose cohort is generated by an
  // event under the overlap policy, contribute nothing.
  var estimates = input.studentLocationEstimates || [];
  for (i = 0; i < estimates.length; i++) {
    var est = estimates[i];
    if (policyFacts.suppressedEstimateIds[est.id]) { continue; }
    if (!est.originStopId || !est.destinationStopId) { continue; }

    var estWeight = weightForEstimate(est, policyFacts, input);
    emitLeg({
      journeys: journeys, trace: trace, rng: rng, assumptions: a,
      sourceKind: 'LocationEstimate', sourceId: est.id, legKind: 'Direct',
      attendance: est.predictedStudentCount, busUseShare: 1.0, weight: estWeight,
      originDist: [SimStopShare.make({ stopId: est.originStopId, share: 1.0 })],
      destDist: [SimStopShare.make({ stopId: est.destinationStopId, share: 1.0 })],
      windowStartMs: msOf(est.arrivalWindowStart),
      windowEndMs: msOf(est.arrivalWindowEnd),
      deadlineMs: est.classStartTime ? msOf(est.classStartTime) : null,
      cohortId: est.cohortId,
      policy: policyFacts.reliabilityPolicy,
      relocation: relocation,
      horizonStartMs: horizonStartMs, horizonEndMs: horizonEndMs
    });
  }

  // Ordering is part of the contract: request time, then journey id. Every consumer therefore
  // walks demand in the same order regardless of the order events were read in.
  journeys.sort(function (x, y) {
    var d = msOf(x.requestTime) - msOf(y.requestTime);
    return d !== 0 ? d : (x.journeyId < y.journeyId ? -1 : (x.journeyId > y.journeyId ? 1 : 0));
  });

  var total = 0;
  var deadlineBearing = 0;
  for (i = 0; i < journeys.length; i++) {
    total += journeys[i].passengerCount;
    if (journeys[i].hasDeadline === true) { deadlineBearing += journeys[i].passengerCount; }
  }

  realizedEventIds.sort();
  unknownAtCutoff.sort();
  suppressedEventIds.sort();

  return SimDemandSnapshot.make({
    snapshotId: snapshotId(input.scenarioId, seed),
    scenarioId: input.scenarioId,
    seed: seed,
    journeys: journeys,
    totalPassengers: total,
    deadlineBearingPassengers: deadlineBearing,
    trace: trace,
    realizedEventIds: realizedEventIds,
    eventIdsUnknownAtCutoff: unknownAtCutoff,
    suppressedEventIds: suppressedEventIds
  });
}

